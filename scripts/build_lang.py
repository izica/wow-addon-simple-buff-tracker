"""Build <addon>/lang/*.lua from <addon>/lang/*.json.

The game cannot read .json files: a .toc loads only .lua and .xml. So every
lang/<language>.json gets a generated lang/<language>.lua next to it, which
hands the JSON text to ns.Localization.Add; json.lua decodes it in game.

Checks on the way, against en.json (the fallback language):
  * the JSON parses;
  * every language has the same keys as en.json;
  * every text has the same %d / %s placeholders as in en.json -- otherwise
    string.format would fail in game.

    python scripts/build_lang.py             lang folder of this repo's addon
    python scripts/build_lang.py my_addon/lang   any other lang folder

ASCII output on purpose: the console here is cp866 and mangles Cyrillic.
"""

import io
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "SimpleBuffTracker", "lang")
FALLBACK = "en"
PLACEHOLDER = re.compile(r"%[-+ #0]*\d*(?:\.\d+)?[dsfgxXq%]")
CLOSE = "]==]"

HEADER = """-- {name}.lua -- generated by scripts/build_lang.py from {name}.json.
-- Do not edit by hand: edit {name}.json and run python scripts/build_lang.py

local ADDON, ns = ...

ns.Localization.Add("{name}", [==[
"""
FOOTER = "]==])\n"


def flatten(tree, prefix=""):
    flat = {}
    for key, value in tree.items():
        path = key if not prefix else prefix + "." + key
        if isinstance(value, dict):
            flat.update(flatten(value, path))
        else:
            flat[path] = value
    return flat


def load(name):
    path = os.path.join(LANG, name + ".json")
    text = io.open(path, encoding="utf-8").read()
    return text, json.loads(text)


def main():
    names = sorted(f[:-5] for f in os.listdir(LANG) if f.endswith(".json"))
    if FALLBACK not in names:
        print("missing %s.json -- it is the fallback language" % FALLBACK)
        return 1

    errors = 0
    reference = flatten(load(FALLBACK)[1])
    for name in names:
        try:
            text, tree = load(name)
        except ValueError as error:
            print("%s.json: bad JSON: %s" % (name, error))
            errors += 1
            continue

        flat = flatten(tree)
        for key in sorted(set(reference) - set(flat)):
            print("%s.json: missing key %s" % (name, key))
            errors += 1
        for key in sorted(set(flat) - set(reference)):
            print("%s.json: extra key %s (not in %s.json)" % (name, key, FALLBACK))
            errors += 1
        for key in sorted(set(flat) & set(reference)):
            if PLACEHOLDER.findall(flat[key]) != PLACEHOLDER.findall(reference[key]):
                print("%s.json: placeholders in %s differ from %s.json" % (name, key, FALLBACK))
                errors += 1
        if CLOSE in text:
            print("%s.json: contains %s, cannot wrap it in a Lua long string" % (name, CLOSE))
            errors += 1
            continue

        body = text if text.endswith("\n") else text + "\n"
        target = os.path.join(LANG, name + ".lua")
        with io.open(target, "w", encoding="utf-8", newline="\n") as out:
            out.write(HEADER.format(name=name) + body + FOOTER)
        print("%s.json -> %s.lua" % (name, name))

    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main())
